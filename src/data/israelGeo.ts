/** Der Gebietsstand, der in einem Jahr gilt: der letzte, der begonnen hat. */
export function snapshotForYear(year: number): Snapshot {
  let found = SNAPSHOTS[0];
  for (const s of SNAPSHOTS) {
    if (s.year <= year) found = s;
    else break;
  }
  return found;
}

